"""Generate docs/dataset_card.md and its chart from the manifests, so its numbers cannot drift.

uv run python data/make_dataset_card.py
"""

from __future__ import annotations

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from wildlens.config import MANIFEST_DIR, ROOT

DOCS = ROOT / "docs"


def table(counts: pd.Series, name: str) -> str:
    lines = [f"| {name} | Files |", "| --- | --- |"]
    lines += [f"| {key} | {value:,} |" for key, value in counts.items()]
    return "\n".join(lines)


def main() -> None:
    species = pd.read_csv(MANIFEST_DIR / "species.csv")
    photos = pd.read_parquet(MANIFEST_DIR / "photos.parquet")
    raw = pd.read_parquet(MANIFEST_DIR / "photos_raw.parquet")
    occurrences = pd.read_parquet(MANIFEST_DIR / "occurrences.parquet")
    far = pd.read_parquet(MANIFEST_DIR / "photos_far_ood.parquet")
    sounds_path = MANIFEST_DIR / "sounds_ready.parquet"
    sounds = pd.read_parquet(sounds_path) if sounds_path.exists() else None

    classifier = photos[photos["role"] == "classifier"]
    per_species = classifier.groupby("species").size().sort_values(ascending=False)
    (DOCS / "images").mkdir(parents=True, exist_ok=True)
    figure, axis = plt.subplots(figsize=(8, 3))
    positions = np.arange(len(per_species))
    axis.bar(positions, per_species.to_numpy(), width=1.0, color="#00805a")
    axis.set_xlabel("Species, most photos first")
    axis.set_ylabel("Photos")
    axis.set_title("Photos per classifier species")
    axis.spines[["top", "right"]].set_visible(False)
    axis.grid(axis="y", alpha=0.3)
    figure.tight_layout()
    figure.savefig(DOCS / "images" / "class_balance.png", dpi=130)

    located = classifier["latitude"].notna().mean()
    dates = pd.to_datetime(classifier["date"], errors="coerce")
    observers = classifier.groupby("observer_id").size().sort_values(ascending=False)
    top_share = observers.head(max(1, len(observers) // 100)).sum() / len(classifier)
    inat_share = occurrences["inat_observation_id"].notna().mean()
    au = occurrences[occurrences["country"] == "AU"]
    threatened = species[(species["role"] == "classifier") & species["threatened"]]["species"]
    sound_section = "Sound recordings have not been downloaded yet."
    if sounds is not None:
        recorded = sounds.groupby("species").size()
        sound_section = (
            f"{len(sounds):,} recordings across {recorded.size} species, "
            f"with a median of {recorded.median():.0f} per species and at most 200. "
            f"{per_species.size - recorded.size} species have none.\n\n"
            + table(sounds["licence"].value_counts(), "Sound licence")
        )

    card = f"""# Dataset card

Generated by `ml/data/make_dataset_card.py`. Do not edit by hand.

## Summary

WildLens trains on Australian bird photos and sounds from iNaturalist and on occurrence records
from GBIF. Images and audio are not stored in this repository. `ml/data/build_dataset.py` regenerates
them, and every file's source, licence and attribution are in its manifest.

| Item | Value |
| --- | --- |
| Classifier species | {per_species.size} |
| Classifier photos after deduplication | {len(classifier):,} |
| Photos per species | {per_species.min()} to {per_species.max()}, median {per_species.median():.0f} |
| Photos removed as duplicate or unreadable | {len(raw) - len(photos):,} |
| Near-OOD photos (Australian birds outside the classifier list) | {(photos["role"] == "ood").sum():,} |
| Far-OOD photos (other wildlife, plants and fungi) | {len(far):,} |
| Occurrence records | {len(occurrences):,}, of which {len(au):,} in Australia |

![Photos per species](images/class_balance.png)

## Sources and licences

- **Photos and species list:** iNaturalist API, with files from its AWS open data bucket. One
  research-grade photo per observation. Only CC0, CC BY and CC BY-NC are accepted.
- **Sounds:** iNaturalist API. CC0, CC BY, CC BY-NC, CC BY-SA and CC BY-NC-SA are accepted, with
  no-derivatives licences rejected.
- **Occurrences and conservation status:** GBIF, with records under each dataset's own licence.
- **Climate:** NASA NEX-GDDP-CMIP6 monthly ensemble statistics, CC0.

All of these sources need no login. Because the training data includes non-commercial licences, the
models are for non-commercial use.

{table(classifier["licence"].value_counts(), "Photo licence")}

## Sound

{sound_section}

## Splits

| Split | Train | Validation | Test | Rule |
| --- | --- | --- | --- | --- |
| Random | {(classifier["split_random"] == "train").sum():,} | \
{(classifier["split_random"] == "val").sum():,} | {(classifier["split_random"] == "test").sum():,} | \
Stratified by species, with an observer in only one split per species |
| Geographic | {(classifier["split_geo"] == "train").sum():,} | \
{(classifier["split_geo"] == "val").sum():,} | {(classifier["split_geo"] == "test").sum():,} | \
Whole 2-degree blocks held out |

The geographic split excludes photos without a usable coordinate. Sixty species spread across the
abundance ranking are the tail set. Their training photos are capped at 5, 10 or 20 for the
few-shot experiment, with those sets nested inside one another.

## Known biases

- **Common species only.** Only species with at least 100 usable observations, so the rarest birds are absent.
- **Observer behaviour.** Records cluster near cities and roads, and the top 1% of observers
  contributed {top_share:.0%} of the classifier photos.
- **Recency.** The API pages only the newest 10,000 records per query, so the commonest species skew
  recent. The classifier photos span {dates.min():%Y} to {dates.max():%Y}.
- **Coordinates.** {located:.0%} of classifier photos have a usable location, as obscured or
  imprecise coordinates are removed. Obscuring is common for sensitive species, so they are
  under-represented in the geographic split.
- **Occurrence sources.** {inat_share:.0%} of occurrence records come from iNaturalist. Those
  matching held-out test photos are removed from prior training by observation ID.
- **Conservation status.** Global IUCN categories via GBIF, not Australian listings. Threatened
  species in the classifier set: {", ".join(threatened) or "none"}.

## Regenerate

```bash
cd ml
uv sync --extra train --extra climate
uv run python data/build_dataset.py
uv run python data/prepare_audio.py
uv run python data/build_climate.py
```

Each step is resumable and caches API responses. Photo files download from S3 with eight
connections. API requests and sound files are spaced 1.1 seconds apart.
"""
    (DOCS / "dataset_card.md").write_text(card)
    print("wrote dataset card")


if __name__ == "__main__":
    main()
