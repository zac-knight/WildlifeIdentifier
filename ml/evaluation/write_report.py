"""Generate docs/evaluation.md from docs/metrics/*.json, so every number traces to a script.

uv run python evaluation/write_report.py
"""

from __future__ import annotations

import json
from typing import Any

from wildlens.config import ROOT

METRICS = ROOT / "docs" / "metrics"
NOT_RUN = "Not measured."


def load(name: str) -> dict | None:
    path = METRICS / f"{name}.json"
    return json.loads(path.read_text()) if path.exists() else None


def pct(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.1f}%"


def row(label: str, summary: dict | None) -> str:
    if not summary:
        return f"| {label} | n/a | n/a | n/a | n/a |"
    return (
        f"| {label} | {pct(summary['top1'])} | {pct(summary['top5'])} | {pct(summary['macro'])} | "
        f"{summary['n']:,} |"
    )


HEADER = "| Setup | Top 1 | Top 5 | Macro | Test items |\n| --- | --- | --- | --- | --- |"


def dig(data: Any, *path: str) -> Any:
    for key in path:
        if not isinstance(data, dict):
            return None
        data = data.get(key)
    return data


def main() -> None:
    image, probe = load("image"), load("dinov2_probe")
    fewshot, audio, sdm, export = load("fewshot"), load("audio"), load("sdm"), load("export")
    near = dig(image, "trust", "ood", "near") or {}
    far = dig(image, "trust", "ood", "far") or {}
    sections = [
        "# Evaluation report",
        "Generated by `ml/evaluation/write_report.py` from scripts in `ml/evaluation/` and "
        "`ml/training/`. Do not edit by hand. Macro accuracy weights each species equally. Test "
        "sets are used for reporting only, with settings tuned on validation data.",
        "## Image classifier and location ablation",
        HEADER,
        row("DINOv2 linear probe, random", dig(probe, "random")),
        row("DINOv2 linear probe, geographic", dig(probe, "geo")),
        row("EfficientNetV2-B2, random", dig(image, "random", "test")),
        row("EfficientNetV2-B2, geographic", dig(image, "geographic", "test")),
        row("Image only, located photos, random", dig(image, "random", "fusion", "image_only")),
        row(
            "Image + location, random",
            dig(image, "random", "fusion", "image_plus_prior"),
        ),
        row(
            "Image only, located photos, geographic",
            dig(image, "geographic", "fusion", "image_only"),
        ),
        row(
            "Image + location, geographic",
            dig(image, "geographic", "fusion", "image_plus_prior"),
        ),
        row("Location alone, random", dig(image, "random", "fusion", "prior_alone")),
        "",
        "Fusion: `score(y) = log p(y|image) + weight * log max(prior(y), floor)`. Chosen weight "
        f"{dig(image, 'random', 'fusion', 'weight')} and floor "
        f"{dig(image, 'random', 'fusion', 'floor')} on the random split, and "
        f"{dig(image, 'geographic', 'fusion', 'weight')} and "
        f"{dig(image, 'geographic', 'fusion', 'floor')} on the geographic split.",
        "## Calibration",
        f"Expected calibration error on the random test split: "
        f"{pct(dig(image, 'random', 'calibration', 'ece_before'))} before and "
        f"{pct(dig(image, 'random', 'calibration', 'ece_after'))} after temperature scaling "
        f"(T = {dig(image, 'random', 'temperature')}). After location fusion and a second "
        f"temperature: {pct(dig(image, 'random', 'fusion', 'ece_after_fusion'))}. On the "
        f"geographic split after scaling: "
        f"{pct(dig(image, 'geographic', 'calibration', 'ece_after'))}. Reliability diagrams are on "
        "the app's evaluation page, with bins in `docs/metrics/image.json`.",
        "## Out-of-distribution detection",
        "| Unknowns | Photos | Energy AUROC | Top-probability AUROC | Energy false accept |",
        "| --- | --- | --- | --- | --- |",
        f"| Near (other Australian birds) | {near.get('photos', 'n/a')} | "
        f"{pct(near.get('energy'))} | {pct(near.get('msp'))} | "
        f"{pct(near.get('energy_false_accept'))} |",
        f"| Far (other wildlife, plants, fungi) | {far.get('photos', 'n/a')} | "
        f"{pct(far.get('energy'))} | {pct(far.get('msp'))} | "
        f"{pct(far.get('energy_false_accept'))} |",
        "",
        f"The energy threshold of {dig(image, 'trust', 'ood', 'energy_threshold')} keeps 95% of "
        f"known-species validation photos, and keeps "
        f"{pct(dig(image, 'trust', 'ood', 'kept_known_test'))} on the test set.",
        "## Hierarchical fallback",
        "Thresholds aim for 90% precision at each level on validation data.",
        "```json",
        json.dumps(dig(image, "trust", "fallback_with_location"), indent=1),
        "```",
        "## Long tail and few-shot",
        HEADER,
        row(
            "Tail species, all training photos",
            dig(image, "tail_with_all_images", "tail_species"),
        ),
        row("Tail species, 10 photos, classifier", dig(fewshot, "classifier_alone", "tail")),
        row(
            "Tail species, 10 photos, classifier + prototypes",
            dig(fewshot, "classifier_plus_prototypes", "tail"),
        ),
        row("Tail species, 10 photos, prototypes", dig(fewshot, "prototypes_alone", "tail")),
        row("Other species, classifier", dig(fewshot, "classifier_alone", "head")),
        row(
            "Other species, classifier + prototypes",
            dig(fewshot, "classifier_plus_prototypes", "head"),
        ),
        "## Audio",
        HEADER,
        row("Sound model, random", dig(audio, "test")),
        row("Paired observations, photo", dig(audio, "fusion", "photo")),
        row("Paired observations, sound", dig(audio, "fusion", "sound")),
        row("Paired observations, photo + sound", dig(audio, "fusion", "photo_plus_sound")),
        "",
        f"Paired test observations: {dig(audio, 'fusion', 'paired_test_observations')}. "
        f"Considered large enough to read as a macro comparison: "
        f"{dig(audio, 'fusion', 'reliable')}.",
        "## Species distribution models",
    ]
    if sdm:
        sections += [
            f"Spatial block cross validation (5-degree blocks, {sdm['species_with_cv']} species). "
            f"Median AUC {sdm['auc_median']:.3f} (10th to 90th percentile {sdm['auc_p10']:.3f} to "
            f"{sdm['auc_p90']:.3f}). Median Boyce index {sdm['boyce_median']:.3f} "
            f"({sdm['boyce_p10']:.3f} to {sdm['boyce_p90']:.3f}). "
            f"{sdm['species_too_few_records']} species had too few records to model.",
        ]
    else:
        sections.append(NOT_RUN)
    sections += [
        "## Species card grounding",
        "Unsupported claim rate: not measured. It needs a Gemini API key, which has not been set "
        "up. Without one, the app displays source sentences directly, so no generated claims exist "
        "to check. `ml/evaluation/evaluate_grounding.py` runs this once cards exist.",
        "## Browser performance and download sizes",
        "```json",
        json.dumps(export, indent=1) if export else NOT_RUN,
        "```",
        "Browser latency on a mid-range laptop has not been measured with the final models.",
        "## Limitations",
        "- Only 200 commonly photographed species are covered, so anything else gets a wrong name "
        "unless flagged as unfamiliar.",
        "- Test photos share iNaturalist's biases, so real-world accuracy may be lower.",
        "- Tuning used half of the validation set, so chosen settings carry some sampling noise.",
        "- Prior training data caps per-species records, so it does not reflect true abundance.",
        "- SDMs use climate alone at about 25 km. Land use, dispersal and interactions are absent.",
        "- Ensemble percentile fields are not physically consistent climates, so agreement across "
        "them is only a rough guide to model disagreement.",
        "- The classifier has not been evaluated on real camera trap images.",
    ]
    (ROOT / "docs" / "evaluation.md").write_text(
        "\n\n".join(sections).replace("|\n\n|", "|\n|") + "\n"
    )
    print("wrote evaluation report")


if __name__ == "__main__":
    main()
